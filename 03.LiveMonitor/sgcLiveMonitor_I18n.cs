        private static Dictionary<string, string> GetMap(string aLang)
        {
            Dictionary<string, string> oMap;
            if (FLocales.TryGetValue(aLang == null ? "" : aLang.ToLowerInvariant(), out oMap))
                return oMap;
            return null;
        }

        private static void Register(string aLang, Dictionary<string, string> aMap)
        {
            FLocales[aLang.ToLowerInvariant()] = aMap;
        }

        // Translate aKey for aLang. Falls back to "en", then to the raw key.
        public static string T(string aKey, string aLang = "en")
        {
            string vValue;
            Dictionary<string, string> oMap = GetMap(aLang);
            if (oMap != null && oMap.TryGetValue(aKey, out vValue) && vValue != "")
                return vValue;
            oMap = GetMap("en");
            if (oMap != null && oMap.TryGetValue(aKey, out vValue) && vValue != "")
                return vValue;
            return aKey;
        }

        // True when aLang has a non-empty translation for aKey.
        public static bool HasTranslation(string aKey, string aLang)
        {
            string vValue;
            Dictionary<string, string> oMap = GetMap(aLang);
            return oMap != null && oMap.TryGetValue(aKey, out vValue) && vValue != "";
        }

